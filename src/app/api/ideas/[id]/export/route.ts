import { db } from '@/lib/db'
import { parseInterpretation, parseSummary } from '@/lib/payload'

type Params = { params: Promise<{ id: string }> }

const AREA_LABELS: Record<string, string> = {
  business_problem: 'Business problem',
  target_users: 'Target users',
  product_format: 'Product format',
  business_model: 'Business model',
  user_journeys: 'User journeys',
  scope: 'Scope',
  constraints: 'Constraints',
  success_criteria: 'Success criteria',
  unknowns: 'Unknowns',
}

function esc(v: string): string {
  return v.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

export async function GET(req: Request, { params }: Params) {
  try {
    const { id } = await params
    const format = new URL(req.url).searchParams.get('format') === 'json' ? 'json' : 'md'

    const idea = await db.idea.findUnique({
      where: { id },
      include: {
        questions: { orderBy: [{ order: 'asc' }, { createdAt: 'asc' }] },
        features: { orderBy: [{ order: 'asc' }, { createdAt: 'asc' }] },
        assumptions: { orderBy: { createdAt: 'asc' } },
        decisions: { orderBy: { createdAt: 'desc' } },
      },
    })
    if (!idea) {
      return Response.json({ error: 'Idea not found' }, { status: 404 })
    }

    const interpretation = parseInterpretation(idea.interpretation)
    const summary = parseSummary(idea.summary)
    const answered = idea.questions.filter((q) => q.status === 'answered')
    const accepted = idea.features.filter((f) => f.status === 'accepted')
    const deferred = idea.features.filter((f) => f.status === 'deferred')
    const rejected = idea.features.filter((f) => f.status === 'rejected')

    const slug = (interpretation?.title ?? 'idea')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .slice(0, 50) || 'idea'

    if (format === 'json') {
      const payload = {
        product: 'Blueprint Assistant P0 export',
        exportedAt: new Date().toISOString(),
        idea: {
          id: idea.id,
          title: idea.title,
          originalText: idea.originalText,
          sourceLang: idea.sourceLang,
          stage: idea.stage,
        },
        interpretation,
        discoverySummary: summary,
        discoveryQA: answered.map((q) => ({
          area: q.area,
          question: q.questionEn,
          answer: q.answer,
        })),
        skippedQuestions: idea.questions.filter((q) => q.status === 'skipped').map((q) => q.questionEn),
        featureBaseline: {
          approvedAt: idea.stage === 'baseline' ? idea.updatedAt.toISOString() : null,
          accepted: accepted.map((f) => ({ module: f.module, feature: f.feature, user: f.user, priority: f.priority, rationale: f.rationale })),
          deferred: deferred.map((f) => ({ module: f.module, feature: f.feature, priority: f.priority })),
          rejected: rejected.map((f) => f.feature),
        },
        assumptionRegister: idea.assumptions.map((a) => ({ text: a.text, kind: a.kind, status: a.status, source: a.source })),
        decisionHistory: idea.decisions.map((d) => ({ at: d.createdAt.toISOString(), action: d.action, detail: d.detail, stage: d.stage })),
      }
      return new Response(JSON.stringify(payload, null, 2), {
        headers: {
          'Content-Type': 'application/json; charset=utf-8',
          'Content-Disposition': `attachment; filename="blueprint-${slug}.json"`,
        },
      })
    }

    // ---------- Markdown document (English, professional) ----------
    const lines: string[] = []
    lines.push(`# ${idea.title}`)
    lines.push('')
    lines.push(`> Software Blueprint — P0 discovery baseline. Generated by Blueprint Assistant on ${new Date().toDateString()}.`)
    lines.push('')
    lines.push('## 1. Original Idea')
    lines.push('')
    lines.push(`_${idea.sourceLang === 'ar' ? 'Arabic original, retained as submitted' : 'Original submission'}:_`)
    lines.push('')
    lines.push(`> ${idea.originalText.replace(/\n/g, '\n> ')}`)
    lines.push('')
    if (interpretation) {
      lines.push('## 2. English Interpretation')
      lines.push('')
      lines.push(interpretation.englishInterpretation)
      lines.push('')
      lines.push('## 3. Problem Statement')
      lines.push('')
      lines.push(interpretation.problemStatement)
      lines.push('')
      lines.push('## 4. Confirmed Facts')
      lines.push('')
      for (const u of interpretation.understood) lines.push(`- ${u}`)
      lines.push('')
      if (interpretation.unclear.length > 0) {
        lines.push('## 5. Open Questions from Understanding')
        lines.push('')
        for (const u of interpretation.unclear) lines.push(`- ${u}`)
        lines.push('')
      }
    }
    if (answered.length > 0) {
      lines.push('## 6. Discovery Decisions (Q&A)')
      lines.push('')
      let currentArea = ''
      for (const q of answered) {
        if (q.area !== currentArea) {
          currentArea = q.area
          lines.push(`### ${AREA_LABELS[q.area] ?? q.area}`)
          lines.push('')
        }
        lines.push(`- **Q:** ${q.questionEn}`)
        lines.push(`  **A:** ${q.answer ?? '—'}`)
        lines.push('')
      }
    }
    if (summary) {
      lines.push('## 7. Discovery Summary')
      lines.push('')
      lines.push(summary.summaryMarkdown)
      lines.push('')
      if (summary.openRisks.length > 0) {
        lines.push('**Open risks:**')
        lines.push('')
        for (const r of summary.openRisks) lines.push(`- ${r}`)
        lines.push('')
      }
    }
    if (idea.features.length > 0) {
      lines.push('## 8. Feature Baseline')
      lines.push('')
      if (idea.stage === 'baseline') {
        lines.push(`_Approved on ${idea.updatedAt.toDateString()}._`)
        lines.push('')
      } else {
        lines.push('_Not yet approved — statuses below reflect decisions made so far._')
        lines.push('')
      }
      lines.push('| Module | Feature | User | Priority | Status |')
      lines.push('| --- | --- | --- | --- | --- |')
      const visible = idea.features.filter((f) => f.status !== 'rejected')
      for (const f of visible) {
        lines.push(`| ${esc(f.module)} | ${esc(f.feature)} | ${esc(f.user)} | ${f.priority} | ${f.status.replace('_', ' ')} |`)
      }
      lines.push('')
      if (rejected.length > 0) {
        lines.push(`_Rejected (excluded from baseline): ${rejected.map((f) => f.feature).join('; ')}._`)
        lines.push('')
      }
    }
    if (idea.assumptions.length > 0) {
      lines.push('## 9. Assumption Register')
      lines.push('')
      lines.push('| Assumption | Kind | Status |')
      lines.push('| --- | --- | --- |')
      for (const a of idea.assumptions) {
        lines.push(`| ${esc(a.text)} | ${a.kind} | ${a.status} |`)
      }
      lines.push('')
    }
    if (idea.decisions.length > 0) {
      lines.push('## 10. Decision History')
      lines.push('')
      for (const d of idea.decisions) {
        lines.push(`- **${d.action}** — ${d.createdAt.toISOString().slice(0, 16).replace('T', ' ')}${d.detail ? ` — _${d.detail}_` : ''}`)
      }
      lines.push('')
    }
    lines.push('## 11. Next Steps (P1 engines)')
    lines.push('')
    lines.push('This P0 baseline covers understanding, discovery and the approved feature scope. The next stages are market research (10-competitor comparison), requirements & architecture, and the full engineering document package.')
    lines.push('')

    return new Response(lines.join('\n'), {
      headers: {
        'Content-Type': 'text/markdown; charset=utf-8',
        'Content-Disposition': `attachment; filename="blueprint-${slug}.md"`,
      },
    })
  } catch (error) {
    console.error('[api/ideas/[id]/export GET]', error)
    return Response.json({ error: 'Failed to export the blueprint.' }, { status: 500 })
  }
}
